def _find_nearest_band(freq_ghz: float) -> tuple:
    """最近邻选频段系数（固件 ka256_loss_find_nearest_band）。"""
    return min(_KA256_LOSS_TABLE, key=lambda b: abs(freq_ghz - b[0]))[1]


def ka256_scan_loss_db(freq_ghz: float, offaxis_deg: float) -> float:
    """扫描损失 (dB)。offaxis_deg = 波束离阵面法线角（天顶距）。"""
    offaxis = abs(offaxis_deg)
    if offaxis > KA256_HARD_LIMIT_DEG:
        offaxis = KA256_HARD_LIMIT_DEG
    a = _find_nearest_band(freq_ghz)
    r = a[4]
    r = r * offaxis + a[3]
    r = r * offaxis + a[2]
    r = r * offaxis + a[1]
    r = r * offaxis + a[0]
    return max(0.0, r)
