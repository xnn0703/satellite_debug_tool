"""生成单实例静态更新服务配置；不连接服务器、不修改系统。"""
from __future__ import annotations

import argparse
import ipaddress
from pathlib import Path
import re


def render(host: str, root: str = "/srv/satellite-updates/public") -> str:
    try:
        address = ipaddress.ip_address(host)
        if address.version != 4:
            raise ValueError("the initial deployment uses the ECS public IPv4 address")
    except ValueError:
        if re.fullmatch(r"(?=.{1,253}$)[a-z0-9]+(?:[.-][a-z0-9]+)+", host) is None:
            raise ValueError("host requires a public IPv4 address or DNS name")
    if root != "/srv/satellite-updates/public":
        raise ValueError("the publication root is fixed by the deployment contract")
    return f"""# Generated by render_config.py; load only after nginx -t succeeds.
server {{
    listen 80;
    server_name {host};
    location ^~ /.well-known/acme-challenge/ {{
        root /srv/satellite-updates/acme;
        try_files $uri =404;
    }}
    location / {{ return 301 https://{host}$request_uri; }}
}}
server {{
    listen 443 ssl;
    server_name {host};
    ssl_certificate /etc/letsencrypt/live/{host}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/{host}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    root {root};
    autoindex off;
    sendfile on;
    gzip off;
    max_ranges 1;
    client_max_body_size 1k;
    add_header X-Content-Type-Options nosniff always;
    location = /health.txt {{
        default_type text/plain;
        add_header Cache-Control "no-store";
        return 200 "satellite-update-service ready\\n";
    }}
    location ~ ^/v1/apps/[a-z0-9][a-z0-9-]*/metadata/[A-Za-z0-9.-]+\\.json$ {{
        limit_except GET {{ deny all; }}
        add_header Cache-Control "no-cache" always;
        try_files $uri =404;
    }}
    location ~ ^/v1/apps/[a-z0-9][a-z0-9-]*/targets/ {{
        limit_except GET {{ deny all; }}
        add_header Cache-Control "public, max-age=31536000, immutable" always;
        try_files $uri =404;
    }}
    location ~ ^/downloads/v[0-9][A-Za-z0-9.+-]*/[A-Za-z0-9][A-Za-z0-9._+-]*\\.(7z|zip|json|txt|html)$ {{
        limit_except GET {{ deny all; }}
        add_header Cache-Control "public, max-age=31536000, immutable" always;
        try_files $uri =404;
    }}
    location / {{ return 404; }}
}}
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--host", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    content = render(args.host)
    with args.output.open("x", encoding="utf-8") as stream:
        stream.write(content)


if __name__ == "__main__":
    main()
